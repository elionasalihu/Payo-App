// Payo service worker.
// Create React App compiles this file with Workbox (InjectManifest) during
// `npm run build`, injecting the list of build files into self.__WB_MANIFEST.

import { clientsClaim } from "workbox-core";
import { ExpirationPlugin } from "workbox-expiration";
import { CacheableResponsePlugin } from "workbox-cacheable-response";
import { createHandlerBoundToURL, precacheAndRoute } from "workbox-precaching";
import { registerRoute } from "workbox-routing";
import { CacheFirst, StaleWhileRevalidate } from "workbox-strategies";

clientsClaim();

// 1. Precache the app shell (JS, CSS, HTML) generated by the build.
precacheAndRoute(self.__WB_MANIFEST);

// 2. Single-page-app navigation: serve index.html for every in-app route,
//    so the app opens even when offline.
const fileExtensionRegexp = /[^/?]+\.[^/]+$/;
registerRoute(({ request, url }) => {
  if (request.mode !== "navigate") return false;
  if (url.pathname.startsWith("/_")) return false;
  if (url.pathname.match(fileExtensionRegexp)) return false;
  return true;
}, createHandlerBoundToURL(process.env.PUBLIC_URL + "/index.html"));

// 3. Same-origin images and icons: fast from cache, refreshed in the background.
registerRoute(
  ({ url, request }) => url.origin === self.location.origin && request.destination === "image",
  new StaleWhileRevalidate({
    cacheName: "payo-images",
    plugins: [new ExpirationPlugin({ maxEntries: 50 })],
  })
);

// 4. Google Fonts: stylesheet revalidated, font files cached for a year.
registerRoute(
  ({ url }) => url.origin === "https://fonts.googleapis.com",
  new StaleWhileRevalidate({ cacheName: "payo-font-styles" })
);
registerRoute(
  ({ url }) => url.origin === "https://fonts.gstatic.com",
  new CacheFirst({
    cacheName: "payo-fonts",
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 30, maxAgeSeconds: 60 * 60 * 24 * 365 }),
    ],
  })
);

// Supabase API and auth requests are deliberately NOT cached: balances must
// always be live, and responses contain private data.

// 5. Let the page activate a waiting update immediately ("Update available" → Reload).
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});
